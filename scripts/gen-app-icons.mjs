#!/usr/bin/env node
/**
 * Generate the hero demo's icons from the app's own icon sources.
 *
 *   node scripts/gen-app-icons.mjs <path-to-app>/dodaios/ui/web/frontend
 *
 * Writes two files into src/components/demo/app/:
 *
 *   lucide.tsx        the lucide icons the clone uses, as the app's pinned
 *                     lucide-react version draws them (same nodes, same
 *                     default attributes, same `lucide lucide-<name>` class)
 *   sectionIcons.tsx  the app's own section icons, copied from
 *                     src/components/icons/sectionIcons.tsx
 *
 * This site does not depend on lucide-react: one more package here would need
 * its lockfile re-resolved on Linux (docs/deploy.md), and the clone only needs
 * a few dozen icons, frozen at the app's version.
 *
 * Add a name to ICONS and run it again when the clone needs another icon.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(fileURLToPath(new URL(".", import.meta.url)), "..");
const OUT_DIR = join(ROOT, "src", "components", "demo", "app");

const ICONS = [
  "AppWindow", "ArrowLeft", "ArrowRight", "AudioLines", "Bot", "Check", "ChevronDown",
  "ChevronLeft", "ChevronRight", "Circle", "CircleCheck", "CircleDashed", "Copy", "Download",
  "Ellipsis", "FilePlus2", "FileText", "Folder", "FolderOpen", "GitBranch", "GitPullRequest",
  "Globe", "Keyboard", "LayoutGrid", "Loader", "LoaderCircle", "MessageSquare", "Mic", "Minus",
  "PanelLeftClose", "PanelRightOpen", "PanelRight", "Pencil", "Play", "Plus", "RotateCw", "Search", "Settings",
  "Sparkles", "Square", "SquareTerminal", "Sun", "Terminal", "Wrench", "X",
  // The Agentic IDE scene (IdeScene.tsx).
  "Building2", "CheckCheck", "Eye", "FileDiff", "FolderTree", "Maximize2", "Minimize2", "PanelRightClose",
];

const app = process.argv[2];
if (!app) {
  console.error("usage: node scripts/gen-app-icons.mjs <app>/dodaios/ui/web/frontend");
  process.exit(2);
}

const kebab = (name) =>
  name.replace(/([a-z0-9])([A-Z])/g, "$1-$2").replace(/([A-Z])([A-Z][a-z])/g, "$1-$2").toLowerCase()
    .replace(/([a-z])([0-9])/g, "$1-$2");

const lucideDir = join(app, "node_modules", "lucide-react", "dist", "esm", "icons");
const version = JSON.parse(readFileSync(join(app, "node_modules", "lucide-react", "package.json"), "utf8")).version;

const defs = ICONS.map((name) => {
  const file = kebab(name);
  const src = readFileSync(join(lucideDir, `${file}.js`), "utf8");
  const m = /createLucideIcon\("[^"]+", (\[[\s\S]*?\])\);/.exec(src);
  if (!m) throw new Error(`cannot read ${file}.js`);
  // The nodes are plain JS literals; strip the React keys, keep the rest.
  const nodes = m[1].replace(/,\s*key: "[^"]*"/g, "");
  return `export const ${name} = icon("${file}", ${nodes.replace(/\s+/g, " ")});`;
});

const lucide = `/**
 * GENERATED by scripts/gen-app-icons.mjs from lucide-react v${version} (ISC),
 * the version the app pins. Do not edit by hand.
 */
import { createElement, type SVGProps } from "react";

type Node = [string, Record<string, string>];
export type IconProps = SVGProps<SVGSVGElement> & { size?: number };

function icon(name: string, nodes: Node[]) {
  return function Icon({ size = 24, strokeWidth = 2, className, ...rest }: IconProps) {
    return createElement(
      "svg",
      {
        xmlns: "http://www.w3.org/2000/svg",
        width: size,
        height: size,
        viewBox: "0 0 24 24",
        fill: "none",
        stroke: "currentColor",
        strokeWidth,
        strokeLinecap: "round",
        strokeLinejoin: "round",
        className: ["lucide", \`lucide-\${name}\`, className].filter(Boolean).join(" "),
        ...rest,
      },
      ...nodes.map(([tag, attrs], i) => createElement(tag, { key: i, ...attrs })),
    );
  };
}

${defs.join("\n")}
`;
writeFileSync(join(OUT_DIR, "lucide.tsx"), lucide);

let section = readFileSync(join(app, "src", "components", "icons", "sectionIcons.tsx"), "utf8");
section = section
  .replace(/import type \{ LucideIcon, LucideProps \} from "lucide-react";/, `import type { ReactElement, SVGProps } from "react";
type LucideProps = SVGProps<SVGSVGElement> & { size?: number | string; absoluteStrokeWidth?: boolean };
type LucideIcon = (props: LucideProps) => ReactElement;`)
  .replace(/^\/\*\*/, `/**
 * COPIED by scripts/gen-app-icons.mjs from the app's
 * src/components/icons/sectionIcons.tsx. Do not edit by hand.
 *
 * ---`);
writeFileSync(join(OUT_DIR, "sectionIcons.tsx"), section);
console.log(`lucide.tsx: ${ICONS.length} icons (lucide-react ${version}); sectionIcons.tsx copied`);
